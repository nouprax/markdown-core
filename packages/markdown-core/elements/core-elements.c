#ifndef NDEBUG
/* The facet of `kind` among the elements' declarations, or NULL. */
static const markdown_core_facet *S_facet_find(markdown_core_node_kind kind) {
    for (size_t i = 0; i < CORE_ELEMENT_COUNT; i++) {
        for (const markdown_core_facet *facet = CORE_ELEMENTS[i]->facets;
             facet && facet->kind != MARKDOWN_CORE_KIND_NONE; facet++) {
            if (facet->kind == kind) {
                return facet;
            }
        }
    }
    return NULL;
}
#endif

markdown_core_node *markdown_core_parse_document(const char *buffer, size_t len) {
    return markdown_core_parse_document_with_setup(buffer, len, NULL, NULL);
}

markdown_core_node *markdown_core_parse_document_with_setup(const char *source, size_t length,
                                                            markdown_core_parser_setup_func setup, void *context) {
    markdown_core_parser *parser = markdown_core_core_parser(setup, context);
    if (!parser) {
        return NULL;
    }
    markdown_core_node_pool pool = {0};
    markdown_core_revision revision = {.pool = &pool};
    markdown_core_parser_start(parser, &revision);
    markdown_core_parser_commit(parser, source, length, true);
    markdown_core_node *root = markdown_core_parser_finalize(parser);
    markdown_core_parser_destroy(parser);
    markdown_core_node_pool_dispose(&pool);
    return root;
}

markdown_core_parser *markdown_core_core_parser(markdown_core_parser_setup_func setup, void *context) {
#ifndef NDEBUG
    for (size_t kind = 0; kind < MARKDOWN_CORE_FACET_ROOM; kind++) {
        assert(markdown_core_facet_table[kind] == S_facet_find((markdown_core_node_kind)kind));
    }
#endif
    size_t count;
    const markdown_core_element *const *elements = markdown_core_core_elements(&count);
    return markdown_core_parser_create(elements, count, setup, context);
}

