#!/usr/bin/env node
// Unicode 17 category tables for the dialect's scalar predicates. Regenerate
// with the pinned Node runtime, whose ICU tables supply exactly this Unicode
// version. Every table starts above ASCII: the predicates answer ASCII from
// the ctype classes inline (utf8.h) and enter a table only for other scalars,
// so the tables and the search over them are the non-ASCII path alone.
import fs from "node:fs";
if (process.versions.unicode !== "17.0") throw new Error("Unicode 17.0 is required");
let text = "/* Generated by scripts/generate-unicode-categories.mjs; Unicode 17.0. */\n";
for (const [name, pattern] of [
    ["letter", /\p{L}/u],
    ["number", /\p{N}/u],
    ["mark", /\p{M}/u],
    ["punctuation", /\p{P}/u],
    ["punctuation_or_symbol", /[\p{P}\p{S}]/u]
]) {
    const ranges = [];
    for (let cp = 0x80; cp <= 0x10ffff; cp++) {
        if (cp >= 0xd800 && cp <= 0xdfff) continue;
        if (!pattern.test(String.fromCodePoint(cp))) continue;
        const previous = ranges.at(-1);
        if (previous && previous[1] + 1 === cp) previous[1] = cp;
        else ranges.push([cp, cp]);
    }
    text += `static const int32_t ${name}_ranges[][2] = {\n`;
    text += ranges.map(([a, b]) => `    {0x${a.toString(16)}, 0x${b.toString(16)}}`).join(",\n") + "\n};\n";
    text += `int markdown_core_unicode_${name}(int32_t uc) {\n`;
    text += `    return unicode_range_search(${name}_ranges, sizeof(${name}_ranges) / sizeof(*${name}_ranges), uc);\n}\n`;
}
fs.writeFileSync("packages/markdown-core/core/unicode_categories.inc", text);
