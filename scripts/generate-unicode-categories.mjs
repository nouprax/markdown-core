#!/usr/bin/env node
// Unicode 17 categories used by names in the dialect. Regenerate with the
// pinned Node runtime, whose ICU tables supply exactly this Unicode version.
import fs from "node:fs";
if (process.versions.unicode !== "17.0") throw new Error("Unicode 17.0 is required");
let text = "/* Generated by scripts/generate-unicode-categories.mjs; Unicode 17.0. */\n";
for (const [name, pattern] of [
    ["letter", /\p{L}/u],
    ["number", /\p{N}/u],
    ["mark", /\p{M}/u]
]) {
    const ranges = [];
    for (let cp = 0; cp <= 0x10ffff; cp++) {
        if (!pattern.test(String.fromCodePoint(cp))) continue;
        const previous = ranges.at(-1);
        if (previous && previous[1] + 1 === cp) previous[1] = cp;
        else ranges.push([cp, cp]);
    }
    text += `static const int32_t ${name}_ranges[][2] = {\n`;
    text += ranges.map(([a, b]) => `    {0x${a.toString(16)}, 0x${b.toString(16)}}`).join(",\n") + "\n};\n";
    text += `int markdown_core_utf8proc_is_${name}(int32_t uc) {\n`;
    text += `    size_t low = 0, high = sizeof(${name}_ranges) / sizeof(*${name}_ranges);\n`;
    text += `    while (low < high) {\n        size_t mid = low + (high - low) / 2;\n        if (uc < ${name}_ranges[mid][0]) high = mid;\n        else if (uc > ${name}_ranges[mid][1]) low = mid + 1;\n        else return 1;\n    }\n    return 0;\n}\n`;
}
fs.writeFileSync("packages/markdown-core/core/unicode_categories.inc", text);
