#!/usr/bin/env node
// Write the Rust core's Unicode tables (packages/markdown-core-rs/src/util/tables.rs)
// from the C core's generated tables, so both read the same Unicode 17 data:
// unicode_categories.inc, case_fold.inc, case_fold_index.inc.
//   node scripts/tools/emit-rust-tables.mjs [--check]
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const core = path.join(root, "packages/markdown-core/core");
const dest = path.join(root, "packages/markdown-core-rs/src/util/tables.rs");

const read = (name) =>
    fs
        .readFileSync(path.join(core, name), "utf8")
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .replace(/\/\/.*$/gm, "");

// Each C array becomes a flat Rust array of the same element type.
const tables = (text) => {
    const found = {};
    const pattern = /(?:static\s+)?const\s+(\w+)\s+(\w+)((?:\[\d+\])+)\s*=\s*\{([\s\S]*?)\};/g;
    for (const match of text.matchAll(pattern)) {
        const [, kind, name, dims, inner] = match;
        const values = inner
            .replace(/[{}]/g, " ")
            .split(",")
            .map((value) => value.trim())
            .filter((value) => value.length > 0);
        const sizes = [...dims.matchAll(/\[(\d+)\]/g)].map((size) => Number(size[1]));
        const count = sizes.reduce((a, b) => a * b, 1);
        if (values.length !== count) throw new Error(`${name}: ${values.length} values for ${count}`);
        found[name] = { kind, sizes, values };
    }
    return found;
};

const emit = (rustName, table, kind) => {
    const lines = [];
    for (let index = 0; index < table.values.length; index += 16) {
        lines.push("    " + table.values.slice(index, index + 16).join(", ") + ",");
    }
    return `pub static ${rustName}: [${kind}; ${table.values.length}] = [\n${lines.join("\n")}\n];\n`;
};

const classes = tables(read("unicode_categories.inc"));
const fold = tables(read("case_fold.inc").replace(/unsigned char/g, "uint8_t"));
const index = tables(read("case_fold_index.inc"));

let out = `//! Unicode 17 tables, generated by scripts/tools/emit-rust-tables.mjs
//! from the C core's generated tables; do not edit.
#![allow(clippy::unreadable_literal)]

`;
out += "/// Category classes: `BLOCKS[PAGES[s >> 8] + (s & 255)]`.\n";
out += emit("PAGES", classes.markdown_core_unicode_pages, "u16");
out += emit("BLOCKS", classes.markdown_core_unicode_blocks, "u8");
out +=
    "/// Case folds below `1 << 17`: entry `FOLD_LEAVES[FOLD_PAGES[c >> 6] * 64 + (c & 63)]`, 0 for none, else 1 + index in `FOLDS`.\n";
out += emit("FOLD_PAGES", index.cf_pages, "u8");
out += emit("FOLD_LEAVES", index.cf_leaves, "u16");
out += "/// A fold entry: image offset `((e >> 17) & 0xFFF) * 2` in `FOLD_IMAGES`, length `e >> 29`.\n";
out += emit("FOLDS", fold.cf_table, "u32");
out += emit("FOLD_IMAGES", fold.cf_repl, "u8");

if (process.argv.includes("--check")) {
    if (fs.readFileSync(dest, "utf8") !== out) {
        console.error("tables.rs is stale: run node scripts/tools/emit-rust-tables.mjs");
        process.exit(1);
    }
} else {
    fs.writeFileSync(dest, out);
}
