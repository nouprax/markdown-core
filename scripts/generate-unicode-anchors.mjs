#!/usr/bin/env node
// Supply https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt.
// Compile the anchors module's scalar operation into disjoint affine ranges:
// simple lowercase, White_Space to '-', then retain L/N/M/Pc/'-'.
// Omitted scalars are removed. Builds use the checked-in table, without downloads.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs";

assert.equal(process.versions.unicode, "17.0");
const data = fs.readFileSync(process.argv[2]);
assert.equal(
    createHash("sha256").update(data).digest("hex"),
    "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
);
const lowercase = new Map(
    data
        .toString("utf8")
        .trim()
        .split("\n")
        .map((line) => line.split(";"))
        .filter((fields) => fields[13])
        .map((fields) => [parseInt(fields[0], 16), parseInt(fields[13], 16)])
);
const ranges = [];
for (let scalar = 0; scalar <= 0x10ffff; scalar++) {
    let target = lowercase.get(scalar) ?? scalar;
    const text = String.fromCodePoint(target);
    if (/\p{White_Space}/u.test(text)) target = 0x2d;
    else if (!/[\p{L}\p{N}\p{M}\p{Pc}-]/u.test(text)) continue;
    const delta = target - scalar;
    const previous = ranges.at(-1);
    if (previous && previous[1] + 1 === scalar && previous[2] === delta) previous[1] = scalar;
    else ranges.push([scalar, scalar, delta]);
}
fs.writeFileSync(
    "packages/markdown-core/core/anchor_scalars.inc",
    "/* Generated by scripts/generate-unicode-anchors.mjs; Unicode 17.0.0. */\n" +
        "static const int32_t anchor_scalars[][3] = {\n" +
        ranges
            .map(([first, last, delta]) => `    {0x${first.toString(16)}, 0x${last.toString(16)}, ${delta}}`)
            .join(",\n") +
        "\n};\n"
);
