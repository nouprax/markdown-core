#!/usr/bin/env node
// Index packages/markdown-core/core/case_fold.inc for direct lookup.
//
// That file is the fold data: each entry's code point, the length of its
// replacement and where the replacement's bytes are. It stays exactly as it
// is. This derives a two-stage index over it, so that finding a code point's
// entry is two dependent loads for every scalar below CF_MAX, whatever its
// script, rather than a binary search over the whole table that ASCII never
// paid and every other character did. Builds use the checked-in index.
import assert from "node:assert/strict";
import fs from "node:fs";

const input = "packages/markdown-core/core/case_fold.inc";
const output = "packages/markdown-core/core/case_fold_index.inc";
const source = fs.readFileSync(input, "utf8");

const limit = 1 << Number(/#define CF_MAX\s+\(1 << (\d+)\)/u.exec(source)[1]);
const codeMask = Number(/#define CF_CODE_POINT\(x\)\s+\(\(x\) & (0x[0-9A-Fa-f]+)\)/u.exec(source)[1]);
const entries = /static const uint32_t cf_table\[(\d+)\] = \{([^}]*)\}/u.exec(source);
const table = entries[2]
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean)
    .map(Number);
assert.equal(table.length, Number(entries[1]), "the table's declared size");
assert.ok(table.length < 0xffff, "entry numbers fit sixteen bits with zero for no entry");

/* Entry number + 1 for every code point with one, 0 for every other. */
const codes = table.map((entry) => entry & codeMask);
const numbers = new Uint16Array(limit);
codes.forEach((code, i) => {
    assert.ok(i === 0 || codes[i - 1] < code, "the table is sorted by code point without repeats");
    assert.ok(code < limit, "every code point is below CF_MAX");
    numbers[code] = i + 1;
});

/* Leaves of 2^bits code points, interned in first-occurrence order; the page
 * table names a leaf for each run. The leaf size is whichever is smallest. */
function stage(bits) {
    const size = 1 << bits;
    const leafIndex = new Map();
    const leaves = [];
    const pages = [];
    for (let first = 0; first < limit; first += size) {
        const key = numbers.subarray(first, first + size).join(",");
        if (!leafIndex.has(key)) {
            leafIndex.set(key, leaves.length);
            leaves.push(key.split(",").map(Number));
        }
        pages.push(leafIndex.get(key));
    }
    const pageBytes = leaves.length <= 256 ? 1 : 2;
    return { bits, leaves, pages, pageBytes, bytes: pages.length * pageBytes + leaves.length * size * 2 };
}
const best = [3, 4, 5, 6, 7, 8].map(stage).reduce((a, b) => (b.bytes < a.bytes ? b : a));

/* The index answers every code point exactly as the binary search did. */
const search = (c) => {
    let low = 0;
    let high = codes.length;
    while (low < high) {
        const mid = (low + high) >> 1;
        if (c < codes[mid]) high = mid;
        else if (c > codes[mid]) low = mid + 1;
        else return mid + 1;
    }
    return 0;
};
for (let c = 0; c < limit; c++) {
    assert.equal(best.leaves[best.pages[c >> best.bits]][c & ((1 << best.bits) - 1)], search(c));
}

const rows = (values, perLine) => {
    const lines = [];
    for (let i = 0; i < values.length; i += perLine) lines.push(`    ${values.slice(i, i + perLine).join(", ")}`);
    return lines.join(",\n");
};
const pageType = best.pageBytes === 1 ? "uint8_t" : "uint16_t";
fs.writeFileSync(
    output,
    "/* Generated by scripts/tooling/generate-case-fold-index.mjs from case_fold.inc.\n" +
        " *\n" +
        ` * cf_leaves[cf_pages[c >> ${best.bits}]][c & ${(1 << best.bits) - 1}] is 0 when c, below CF_MAX, has no fold,\n` +
        " * and otherwise one more than its entry's position in cf_table. */\n" +
        `#define CF_LEAF_BITS ${best.bits}\n` +
        `static const ${pageType} cf_pages[${best.pages.length}] = {\n${rows(best.pages, 24)}\n};\n` +
        `static const uint16_t cf_leaves[${best.leaves.length}][${1 << best.bits}] = {\n` +
        best.leaves.map((leaf) => `    {${leaf.join(", ")}}`).join(",\n") +
        "\n};\n"
);
console.log(
    `${output}: ${best.leaves.length} leaves of ${1 << best.bits}, ${best.pages.length} ${pageType} pages, ${best.bytes} bytes`
);
