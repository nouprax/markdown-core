#!/usr/bin/env node
// Supply https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt.
// Compile the anchors module's scalar operation: simple lowercase,
// White_Space to '-', then retain L/N/M/Pc/'-'. Omitted scalars are removed.
// The operation is emitted as a three-stage direct table so that a lookup is
// three dependent loads for every scalar, whatever its script.
// Builds use the checked-in table, without downloads.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs";

assert.equal(process.versions.unicode, "17.0");
const data = fs.readFileSync(process.argv[2]);
assert.equal(
    createHash("sha256").update(data).digest("hex"),
    "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
);
const lowercase = new Map(
    data
        .toString("utf8")
        .trim()
        .split("\n")
        .map((line) => line.split(";"))
        .filter((fields) => fields[13])
        .map((fields) => [parseInt(fields[0], 16), parseInt(fields[13], 16)])
);

const SCALARS = 0x110000;
const encodedLength = (scalar) => (scalar < 0x80 ? 1 : scalar < 0x800 ? 2 : scalar < 0x10000 ? 3 : 4);

/* Class 0 removes the scalar; class k > 0 maps it to scalar + deltas[k]. */
const deltas = [0];
const deltaClass = new Map();
const classes = new Uint8Array(SCALARS);
for (let scalar = 0; scalar < SCALARS; scalar++) {
    let target = lowercase.get(scalar) ?? scalar;
    const text = String.fromCodePoint(target);
    if (/\p{White_Space}/u.test(text)) target = 0x2d;
    else if (!/[\p{L}\p{N}\p{M}\p{Pc}-]/u.test(text)) continue;
    /* The consumer reserves 3/2 of a valid literal's length for its image. */
    assert.ok(2 * encodedLength(target) <= 3 * encodedLength(scalar), `U+${scalar.toString(16)} grows past 3/2`);
    const delta = target - scalar;
    if (!deltaClass.has(delta)) {
        deltaClass.set(delta, deltas.length);
        deltas.push(delta);
    }
    classes[scalar] = deltaClass.get(delta);
}
assert.ok(deltas.length <= 256, "delta classes fit a byte");

/* Leaves of LEAF scalars, pages of PAGE leaves, in first-occurrence order. */
const LEAF_BITS = 4;
const PAGE_BITS = 6;
const LEAF = 1 << LEAF_BITS;
const PAGE = 1 << PAGE_BITS;
const intern = (index, key, values) => {
    if (!index.has(key)) {
        index.set(key, index.size);
        values.push(key);
    }
    return index.get(key);
};
const leafIndex = new Map();
const leaves = [];
const leafOf = [];
for (let first = 0; first < SCALARS; first += LEAF) {
    leafOf.push(intern(leafIndex, classes.subarray(first, first + LEAF).join(","), leaves));
}
const pageIndex = new Map();
const pages = [];
const pageOf = [];
for (let first = 0; first < leafOf.length; first += PAGE) {
    pageOf.push(intern(pageIndex, leafOf.slice(first, first + PAGE).join(","), pages));
}
assert.ok(pages.length <= 256, "pages fit a byte");
assert.ok(leaves.length <= 65536, "leaves fit sixteen bits");

/* The staged table answers every scalar exactly as the per-scalar pass did. */
const leafRows = leaves.map((key) => key.split(",").map(Number));
const pageRows = pages.map((key) => key.split(",").map(Number));
for (let scalar = 0; scalar < SCALARS; scalar++) {
    const leaf = pageRows[pageOf[scalar >> (LEAF_BITS + PAGE_BITS)]][(scalar >> LEAF_BITS) & (PAGE - 1)];
    assert.equal(leafRows[leaf][scalar & (LEAF - 1)], classes[scalar]);
}

const rows = (values, perLine) => {
    const lines = [];
    for (let i = 0; i < values.length; i += perLine) lines.push(`    ${values.slice(i, i + perLine).join(", ")}`);
    return lines.join(",\n");
};
const nested = (table) => table.map((row) => `    {${row.join(", ")}}`).join(",\n");
fs.writeFileSync(
    "packages/markdown-core/core/anchor_scalars.inc",
    "/* Generated by scripts/tooling/generate-unicode-anchors.mjs; Unicode 17.0.0.\n" +
        " *\n" +
        " * A scalar's class is anchor_classes[anchor_leaves[anchor_pages[s >> 10]]\n" +
        " * [(s >> 4) & 63]][s & 15]; class 0 removes it and class k maps it to\n" +
        " * s + anchor_deltas[k]. No image is longer than 3/2 of its scalar's UTF-8. */\n" +
        `#define ANCHOR_LEAF_BITS ${LEAF_BITS}\n` +
        `#define ANCHOR_PAGE_BITS ${PAGE_BITS}\n` +
        `static const int32_t anchor_deltas[${deltas.length}] = {\n${rows(deltas, 12)}\n};\n` +
        `static const uint8_t anchor_pages[${pageOf.length}] = {\n${rows(pageOf, 24)}\n};\n` +
        `static const uint16_t anchor_leaves[${pages.length}][${PAGE}] = {\n${nested(pageRows)}\n};\n` +
        `static const uint8_t anchor_classes[${leaves.length}][${LEAF}] = {\n${nested(leafRows)}\n};\n`
);
