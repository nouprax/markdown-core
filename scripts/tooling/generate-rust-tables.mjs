#!/usr/bin/env node
// Write the Rust core's Unicode tables (packages/markdown-core-rs/src/util/tables.rs)
// from the C core's generated tables, so both read the same Unicode 17 data:
// unicode_categories.inc, anchor_scalars.inc, case_fold.inc, case_fold_index.inc.
//   node scripts/tooling/generate-rust-tables.mjs [--check]
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const core = path.join(root, "packages/markdown-core/core");
const target = path.join(root, "packages/markdown-core-rs/src/util/tables.rs");

const read = (name) => fs.readFileSync(path.join(core, name), "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");

// Each C array becomes a flat Rust array of the same element type.
const arrays = (text) => {
    const found = {};
    const pattern = /(?:static\s+)?const\s+(\w+)\s+(\w+)((?:\[\d+\])+)\s*=\s*\{([\s\S]*?)\};/g;
    for (const match of text.matchAll(pattern)) {
        const [, type, name, dims, body] = match;
        const values = body.replace(/[{}]/g, " ").split(",").map((value) => value.trim()).filter((value) => value.length > 0);
        const sizes = [...dims.matchAll(/\[(\d+)\]/g)].map((size) => Number(size[1]));
        const count = sizes.reduce((a, b) => a * b, 1);
        if (values.length !== count) throw new Error(`${name}: ${values.length} values for ${count}`);
        found[name] = { type, sizes, values };
    }
    return found;
};

const rustType = { uint8_t: "u8", uint16_t: "u16", uint32_t: "u32", int32_t: "i32", "unsigned": "u8" };
const emit = (rustName, array, type) => {
    const lines = [];
    for (let index = 0; index < array.values.length; index += 16) {
        lines.push("    " + array.values.slice(index, index + 16).join(", ") + ",");
    }
    return `pub static ${rustName}: [${type}; ${array.values.length}] = [\n${lines.join("\n")}\n];\n`;
};

const categories = arrays(read("unicode_categories.inc"));
const anchors = arrays(read("anchor_scalars.inc"));
const fold = arrays(read("case_fold.inc").replace(/unsigned char/g, "uint8_t"));
const index = arrays(read("case_fold_index.inc"));

let out = `//! Unicode 17 tables, generated by scripts/tooling/generate-rust-tables.mjs
//! from the C core's generated tables; do not edit.
#![allow(clippy::unreadable_literal)]

`;
out += "/// Category classes: `BLOCKS[PAGES[s >> 8] + (s & 255)]`.\n";
out += emit("PAGES", categories.markdown_core_unicode_pages, "u16");
out += emit("BLOCKS", categories.markdown_core_unicode_blocks, "u8");
out += "/// Anchor images: class `CLASSES[LEAVES[PAGES[s >> 10] * 64 + ((s >> 4) & 63)] * 16 + (s & 15)]`, 0 removes.\n";
out += emit("ANCHOR_DELTAS", anchors.anchor_deltas, "i32");
out += emit("ANCHOR_PAGES", anchors.anchor_pages, "u8");
out += emit("ANCHOR_LEAVES", anchors.anchor_leaves, "u16");
out += emit("ANCHOR_CLASSES", anchors.anchor_classes, "u8");
out += "/// Case folds below `1 << 17`: entry `FOLD_LEAVES[FOLD_PAGES[c >> 6] * 64 + (c & 63)]`, 0 for none, else 1 + index in `FOLDS`.\n";
out += emit("FOLD_PAGES", index.cf_pages, "u8");
out += emit("FOLD_LEAVES", index.cf_leaves, "u16");
out += "/// A fold entry: image offset `((e >> 17) & 0xFFF) * 2` in `FOLD_IMAGES`, length `e >> 29`.\n";
out += emit("FOLDS", fold.cf_table, "u32");
out += emit("FOLD_IMAGES", fold.cf_repl, "u8");

if (process.argv.includes("--check")) {
    if (fs.readFileSync(target, "utf8") !== out) {
        console.error("tables.rs is stale: run node scripts/tooling/generate-rust-tables.mjs");
        process.exit(1);
    }
} else {
    fs.writeFileSync(target, out);
}
