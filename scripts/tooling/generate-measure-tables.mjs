#!/usr/bin/env node
// Tables for packages/markdown-core/core/measure.h.
//
// A measure weighs byte i of a run by G^i modulo the prime P = 2^61 - 1
// (measure.h, A MEASURE). G is a fixed residue of large multiplicative order,
// so no short pattern of byte changes cancels by construction. The tables give, for each
// of the eight bytes of a word, every byte's weighted value, and the powers
// of G and of its inverse by one byte of an exponent at a time, so that a
// word is measured in eight loads and a run is moved past another in at most
// four products. Builds use the checked-in tables.
import assert from "node:assert/strict";
import fs from "node:fs";

// Included by map.c alone; measure.h declares the tables.
const output = "packages/markdown-core/core/measure_tables.inc";
const P = (1n << 61n) - 1n;

const mul = (a, b) => (a * b) % P;
function pow(base, exponent) {
    let result = 1n;
    for (let b = base % P, e = exponent; e > 0n; e >>= 1n, b = mul(b, b)) {
        if (e & 1n) {
            result = mul(result, b);
        }
    }
    return result;
}

/* P - 1 = 2 * 3^2 * 5^2 * 7 * 11 * 13 * 31 * 41 * 61 * 151 * 331 * 1321: G
 * has order P - 1 when no G^((P - 1) / q) is 1. */
const factors = [2n, 3n, 5n, 7n, 11n, 13n, 31n, 41n, 61n, 151n, 331n, 1321n];
assert.equal(
    factors.reduce((product, q) => {
        let n = P - 1n;
        while (n % q === 0n) {
            n /= q;
            product *= q;
        }
        return product;
    }, 1n),
    P - 1n,
    "the factors are all of P - 1's"
);
/* G is the first generator from an arbitrary start. */
let G = 0x0f3ac6b15d27e489n;
while (factors.some((q) => pow(G, (P - 1n) / q) === 1n)) {
    G++;
}

const inverse = pow(G, P - 2n);
assert.equal(mul(G, inverse), 1n);

const hex = (value) => "UINT64_C(0x" + value.toString(16).padStart(16, "0") + ")";
function table(name, rows, cell) {
    const lines = [];
    for (let row = 0; row < rows; row++) {
        const cells = [];
        for (let v = 0; v < 256; v++) {
            cells.push(hex(cell(row, BigInt(v))));
        }
        const wrapped = [];
        for (let i = 0; i < cells.length; i += 3) {
            wrapped.push("        " + cells.slice(i, i + 3).join(", ") + ",");
        }
        lines.push("    {\n" + wrapped.join("\n") + "\n    },");
    }
    return `const uint64_t ${name}[${rows}][256] = {\n${lines.join("\n")}\n};\n`;
}

const text =
    "/* Generated by scripts/tooling/generate-measure-tables.mjs.\n" +
    " *\n" +
    ` * G = 0x${G.toString(16)}, a generator of the residues modulo 2^61 - 1.\n` +
    " * markdown_core_measure_terms[k][b] is b G^k; markdown_core_measure_powers\n" +
    " * [j][v] is G^(v 256^j) and markdown_core_measure_inverses[j][v] its\n" +
    " * inverse. Included by map.c alone; measure.h declares them. */\n\n" +
    table("markdown_core_measure_terms", 8, (k, b) => mul(b, pow(G, BigInt(k)))) +
    "\n" +
    table("markdown_core_measure_powers", 4, (j, v) => pow(G, v << (8n * BigInt(j)))) +
    "\n" +
    table("markdown_core_measure_inverses", 4, (j, v) => pow(inverse, v << (8n * BigInt(j))));

fs.writeFileSync(output, text);
