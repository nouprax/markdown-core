#!/usr/bin/env node
// Compile the Unicode character classes the grammar asks about into one
// staged table, from Unicode 17. Regenerate with the pinned Node runtime,
// whose ICU tables supply exactly this Unicode version; builds use the
// checked-in table, without downloads.
//
// Every class is a bit of one byte per scalar (utf8.h names them):
//   space        Zs, and tab, LF, form feed and CR: CommonMark's Unicode
//                whitespace;
//   punctuation  P, and every ASCII punctuation character;
//   symbol       S;
//   letter       L;
//   number       N.
// A scalar's classes are blocks[pages[s >> 8] + (s & 255)]. The first page's
// block is laid first, at offset 0, so utf8.h reads an ASCII character's
// classes with one load and every other scalar's with two, whatever its
// script.
import assert from "node:assert/strict";
import { Buffer } from "node:buffer";
import fs from "node:fs";

assert.equal(process.versions.unicode, "17.0", "Unicode 17.0 is required");

const SPACE = 1 << 0;
const PUNCTUATION = 1 << 1;
const SYMBOL = 1 << 2;
const LETTER = 1 << 3;
const NUMBER = 1 << 4;

const SCALARS = 0x110000;
const asciiPunctuation = (scalar) =>
    (scalar >= 0x21 && scalar <= 0x2f) ||
    (scalar >= 0x3a && scalar <= 0x40) ||
    (scalar >= 0x5b && scalar <= 0x60) ||
    (scalar >= 0x7b && scalar <= 0x7e);
const classesOf = (scalar) => {
    if (scalar >= 0xd800 && scalar <= 0xdfff) return 0;
    const text = String.fromCodePoint(scalar);
    let value = 0;
    if (/\p{Zs}/u.test(text) || scalar === 0x09 || scalar === 0x0a || scalar === 0x0c || scalar === 0x0d) {
        value |= SPACE;
    }
    if (/\p{P}/u.test(text) || asciiPunctuation(scalar)) value |= PUNCTUATION;
    if (/\p{S}/u.test(text)) value |= SYMBOL;
    if (/\p{L}/u.test(text)) value |= LETTER;
    if (/\p{N}/u.test(text)) value |= NUMBER;
    return value;
};
const classes = new Uint8Array(SCALARS);
for (let scalar = 0; scalar < SCALARS; scalar++) classes[scalar] = classesOf(scalar);

/* The text scanner's backward search for white space (elements/text.c)
 * decodes only a character whose lead byte is C2 or E1-E3, the lead bytes of
 * every non-ASCII space. */
for (let scalar = 0x80; scalar < SCALARS; scalar++) {
    if (!(classes[scalar] & SPACE)) continue;
    const lead = Buffer.from(String.fromCodePoint(scalar), "utf8")[0];
    assert.ok(lead === 0xc2 || (lead >= 0xe1 && lead <= 0xe3), `U+${scalar.toString(16)} breaks text.c's lead bytes`);
}

/* Blocks of 1 << bits scalars, interned in first-occurrence order and laid
 * end to end; a page holds the offset of the block for each run of that many
 * scalars, so a lookup adds the scalar's place in its block without scaling
 * the page. */
const stage = (bits) => {
    const size = 1 << bits;
    const index = new Map();
    const blocks = [];
    const pages = [];
    for (let first = 0; first < SCALARS; first += size) {
        const values = Array.from(classes.subarray(first, first + size));
        const key = values.join(",");
        if (!index.has(key)) {
            index.set(key, blocks.length);
            blocks.push(values);
        }
        pages.push(index.get(key) * size);
    }
    return { blocks, pages, flat: blocks.flat(), bytes: pages.length * 2 + blocks.length * size };
};

/* utf8.h shifts by BLOCK_BITS: of the layouts whose offsets fit 16 bits, it is
 * the smallest. */
const BLOCK_BITS = 8;
const BLOCK = 1 << BLOCK_BITS;
const { blocks, pages, flat, bytes } = stage(BLOCK_BITS);
assert.ok(flat.length <= 0x10000, "a page holds its block's offset in 16 bits");
for (let bits = 4; bits <= 12; bits++) {
    const other = stage(bits);
    assert.ok(other.flat.length > 0x10000 || other.bytes >= bytes, `${1 << bits}-scalar blocks are smaller`);
}
assert.equal(pages[0], 0, "ASCII's block is laid first, where utf8.h reads it without its page");

/* The table answers every scalar exactly as the definition above. */
for (let scalar = 0; scalar < SCALARS; scalar++) {
    assert.equal(flat[pages[scalar >> BLOCK_BITS] + (scalar & (BLOCK - 1))], classes[scalar]);
}

const lines = (values, perLine) => {
    const out = [];
    for (let i = 0; i < values.length; i += perLine) out.push(`    ${values.slice(i, i + perLine).join(", ")}`);
    return out.join(",\n");
};
fs.writeFileSync(
    "packages/markdown-core/core/unicode_categories.inc",
    "/* Generated by scripts/tooling/generate-unicode-categories.mjs; Unicode 17.0.\n" +
        " *\n" +
        " * The classes of scalar s below 0x110000 (utf8.h) are\n" +
        " * markdown_core_unicode_blocks[markdown_core_unicode_pages[s >> 8] + (s & 255)]. */\n" +
        `const uint16_t markdown_core_unicode_pages[${pages.length}] = {\n${lines(pages, 16)}\n};\n` +
        `const uint8_t markdown_core_unicode_blocks[${flat.length}] = {\n` +
        blocks.map((block) => lines(block, 32)).join(",\n") +
        "\n};\n"
);
console.log(`unicode_categories.inc: ${pages.length} pages, ${blocks.length} blocks of ${BLOCK}, ${bytes} bytes`);
